type Language = 'th' | 'en';

// 🟢 กำหนด Type ให้ Context ยืดหยุ่นขึ้น (รับค่าเป็น any หรือ string ได้)
interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: any) => string; 
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  // ดึงภาษาเดิมที่เคยเลือกไว้ ถ้าไม่มีให้เริ่มที่ 'th'
  const [language, setLanguageState] = useState<Language>(
    (localStorage.getItem('app_language') as Language) || 'th'
  );

  // ฟังก์ชันเปลี่ยนภาษาและบันทึกลง Local Storage
  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('app_language', lang);
  };

  // 🟢 ฟังก์ชัน t (Translate) ปรับให้อนุโลมการรับค่า
  const t = (key: any) => {
    const dict = translations[language] as Record<string, string>;
    return dict[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};